/**
 * Campaign Match data (web: "You're not the only one"). Built from the synthetic message dataset
 * (data/messages) and the sample indicators by scripts/build-campaign-samples.ts; the result is
 * campaign-samples.json, loaded by the web app only when a result needs it.
 *
 * - counts: scam messages per category in the whole dataset, and in how many languages. A plain
 *   fact about the dataset, so every split counts.
 * - samples: the texts the closest-example search runs over. Train split only, so validation and
 *   test messages are never shown or searched.
 * - campaignOf: the network campaign most of a category's sample indicators belong to.
 * - channelsOf: how the dataset's scam messages of each category arrived (sms, whatsapp, call, …),
 *   for the channels ring on the Network view.
 */
import type { ScamCategory } from '@akshi/contracts';

export interface DatasetRow {
  text: string;
  lang: string;
  label: string;
  category: string | null;
  split: string;
  /** sms, whatsapp, call, telegram, email */
  channel: string;
}
export interface IndicatorRow {
  category?: string;
  campaign?: string;
}

/** [category, lang, text, channel] */
export type CampaignSample = [ScamCategory, string, string, string];

export interface CampaignSamples {
  note: string;
  campaignOf: Partial<Record<ScamCategory, string>>;
  counts: Partial<Record<ScamCategory, { messages: number; langs: number }>>;
  channelsOf: Partial<Record<ScamCategory, Record<string, number>>>;
  samples: CampaignSample[];
}

export const SAMPLE_TEXT_MAX = 240;

/** Keep a sample short for display: cut at a word boundary and mark the cut. */
export function trimSample(text: string, max = SAMPLE_TEXT_MAX): string {
  const t = text.replace(/\s+/g, ' ').trim();
  if (t.length <= max) return t;
  const cut = t.slice(0, max - 1);
  const space = cut.lastIndexOf(' ');
  return `${(space > max * 0.6 ? cut.slice(0, space) : cut).trimEnd()}…`;
}

export function buildCampaignSamples(
  rows: readonly DatasetRow[],
  indicators: readonly IndicatorRow[],
): CampaignSamples {
  const scams = rows.filter((r) => r.label === 'scam' && r.category);

  const counts: CampaignSamples['counts'] = {};
  const langs = new Map<string, Set<string>>();
  for (const r of scams) {
    const c = r.category as ScamCategory;
    counts[c] = { messages: (counts[c]?.messages ?? 0) + 1, langs: 0 };
    langs.set(c, (langs.get(c) ?? new Set()).add(r.lang));
  }
  for (const [c, set] of langs) counts[c as ScamCategory]!.langs = set.size;

  const votes = new Map<string, Map<string, number>>();
  for (const i of indicators) {
    if (!i.category || !i.campaign) continue;
    const v = votes.get(i.category) ?? new Map<string, number>();
    v.set(i.campaign, (v.get(i.campaign) ?? 0) + 1);
    votes.set(i.category, v);
  }
  const campaignOf: CampaignSamples['campaignOf'] = {};
  for (const [category, v] of [...votes].sort(([a], [b]) => a.localeCompare(b))) {
    // most indicators wins; ties go to the alphabetically first campaign, so the build is stable
    const best = [...v].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))[0]!;
    campaignOf[category as ScamCategory] = best[0];
  }

  const channelsOf: CampaignSamples['channelsOf'] = {};
  for (const r of scams) {
    const c = r.category as ScamCategory;
    const m = (channelsOf[c] ??= {});
    m[r.channel] = (m[r.channel] ?? 0) + 1;
  }

  const samples: CampaignSample[] = scams
    .filter((r) => r.split === 'train')
    .map((r) => [r.category as ScamCategory, r.lang, trimSample(r.text), r.channel]);

  return {
    note: 'Generated by scripts/build-campaign-samples.ts from data/messages (synthetic, train split for samples). Do not edit by hand.',
    campaignOf,
    counts: Object.fromEntries(
      Object.entries(counts).sort(([a], [b]) => a.localeCompare(b)),
    ) as CampaignSamples['counts'],
    channelsOf: Object.fromEntries(
      Object.entries(channelsOf)
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([c, m]) => [
          c,
          Object.fromEntries(Object.entries(m).sort(([a], [b]) => a.localeCompare(b))),
        ]),
    ) as CampaignSamples['channelsOf'],
    samples,
  };
}
